"""LLM-as-judge 用的 prompt：評分 decoder 生成的敘述文字跟正確答案（y_belief）像不像。

為什麼需要這個，不能只看 loss/BLEU 這類自動指標：loss 只反映「逐字猜對的機率」，
不反映「生成的內容是否真的講對事情」；BLEU/ROUGE 這類字面重疊度量對開放式生成文字
的評分跟人類判斷的相關性很弱（同一件事換句話說，字面重疊率會很低，但內容其實是對的）。
2026 年評估 LLM 生成品質的共識做法是搭配 LLM-as-judge：用另一個 LLM 依照固定的評分
準則去讀兩段文字、判斷內容是否一致，比字面比對更貼近實際想問的問題「這段生成的敘述
有沒有講對」。

這不是要判斷「哪個模型比較會寫作文」，是判斷「生成的敘述有沒有跟正確答案在講同一件事、
資訊有沒有錯誤或遺漏」，見 SYSTEM_PROMPT 的評分準則。
"""

SYSTEM_PROMPT = """你是評審員，任務是比較「模型生成的市場敘述文字」跟「正確答案的市場敘述文字」，
判斷兩者講的是不是同一件事，內容有沒有錯誤或遺漏。

這兩段文字可能用詞不同、順序不同，重點是「傳達的市場資訊是否一致」，不是要求逐字一樣。

## 評分準則（1~5 分）

- 5 分：內容幾乎一致，關鍵資訊（提到的事件、風險判斷依據）都對得上，沒有錯誤或遺漏。
- 4 分：大部分內容一致，有些細節遺漏但沒有錯誤資訊。
- 3 分：方向大致對，但有明顯的細節出入或遺漏了重要資訊。
- 2 分：只有少部分內容對得上，大部分是無關或錯誤的資訊。
- 1 分：內容跟正確答案矛盾、或完全講不同的事情。

## 輸出格式

只輸出一個 JSON 物件，不要其他文字說明：

{"score": 4, "reason": "簡短說明評分理由"}
"""


def build_user_prompt(ground_truth: str, generated: str) -> str:
    return (
        f"## 正確答案\n{ground_truth}\n\n"
        f"## 模型生成的內容\n{generated}\n\n"
        "依上述兩段文字，評分並輸出 JSON。"
    )
